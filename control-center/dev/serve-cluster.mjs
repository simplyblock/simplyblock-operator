// Serves the console from this checkout against a real cluster, for local
// development: the role the image's nginx plays in a pod, using the
// developer's own kubeconfig instead of a ServiceAccount token.
//
// It lives under dev/ rather than deploy/ because nothing here ships: the image
// keeps its nginx proxy, and prepare.mjs copies only what index.html loads.
//
//   browser ──► this server ──┬── /k8s[/<ctx>]/*      ──► kubectl proxy ──► kube-apiserver
//                             ├── /operator/v1/*       ──► kubectl proxy ──► service simplyblock-operator
//                             ├── /helm/v1/*           ──► kubectl proxy ──► service simplyblock-operator
//                             └── /prometheus/api/v1/* ──► kubectl proxy ──► service simplyblock-prometheus
//
// One `kubectl proxy` child runs per context, so whatever authentication the
// kubeconfig uses (tokens, client certificates, exec plugins) works unchanged.
// The operator and Prometheus are reached through the API server's service
// proxy, which needs no port-forward but does need `services/proxy` in the
// namespace. The browser's own Authorization header is dropped: the page always
// sends one, and kubectl would forward it in place of the kubeconfig's.
//
// Every write the console makes lands on the cluster with the kubeconfig's
// permissions. The server listens on loopback and refuses requests whose Host
// is not a loopback name, so another web page cannot reach it by DNS rebinding.
//
// Usage: node dev/serve-cluster.mjs [--listen=127.0.0.1:8080]
//          [--contexts=name=kubeContext,...] [--namespace=simplyblock]
//          [--operator=simplyblock-operator:8080] [--prometheus=simplyblock-prometheus:9090]
import {spawn} from "node:child_process";
import {createReadStream, statSync} from "node:fs";
import http from "node:http";
import path from "node:path";
import {fileURLToPath} from "node:url";

const args = Object.fromEntries(process.argv.slice(2).map(a => {
  const [k, ...v] = a.replace(/^--/, "").split("=");
  return [k, v.length ? v.join("=") : "true"];
}));
const listen = args.listen || "127.0.0.1:8080";
const namespace = args.namespace || "simplyblock";
const operatorSvc = args.operator || "simplyblock-operator:8080";
const prometheusSvc = args.prometheus || "simplyblock-prometheus:9090";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// --contexts=dev=admin@dev,prd=admin@prd names each console context after the
// part before "=" and runs it against the kubeconfig context after it. Without
// it, the console has one context named local, on kubectl's current context.
const contexts = (args.contexts || "").split(",").filter(Boolean).map(spec => {
  const [name, kubeContext] = spec.split("=");
  if (!name || !kubeContext) throw new Error(`--contexts entry "${spec}" is not name=kubeContext`);
  return {name, kubeContext};
});
if (contexts.length === 0) contexts.push({name: "local", kubeContext: ""});

// startProxy runs `kubectl proxy` on a port the kernel picks and resolves with
// that port once kubectl reports it.
function startProxy(ctx) {
  const argv = ["proxy", "--port=0", "--address=127.0.0.1"];
  if (ctx.kubeContext) argv.push(`--context=${ctx.kubeContext}`);
  const child = spawn("kubectl", argv, {stdio: ["ignore", "pipe", "inherit"]});
  children.push(child);
  return new Promise((resolve, reject) => {
    child.on("error", reject);
    child.on("exit", code => reject(new Error(`kubectl proxy for context ${ctx.name} exited with ${code}`)));
    child.stdout.on("data", chunk => {
      const m = /Starting to serve on [^:]+:(\d+)/.exec(String(chunk));
      if (m) resolve(Number(m[1]));
    });
  });
}

const children = [];
const stop = () => { children.forEach(c => c.kill()); process.exit(0); };
process.on("SIGINT", stop);
process.on("SIGTERM", stop);

// get fetches a path through a context's kubectl proxy and resolves with the
// status code alone; it decides which optional upstreams the console is told
// about, as the image's entrypoint does from its environment.
const get = (port, p) => new Promise(resolve => {
  http.get({host: "127.0.0.1", port, path: p}, res => { res.resume(); resolve(res.statusCode); })
    .on("error", () => resolve(0));
});

for (const ctx of contexts) ctx.port = await startProxy(ctx);
const local = contexts[0];
const svcPath = svc => {
  const [name, port] = svc.split(":");
  return `/api/v1/namespaces/${namespace}/services/http:${name}:${port}/proxy`;
};
const svcExists = async svc => await get(local.port, `/api/v1/namespaces/${namespace}/services/${svc.split(":")[0]}`) === 200;
const upstreams = {
  operator: await svcExists(operatorSvc),
  helm: await svcExists(operatorSvc),
  prometheus: await svcExists(prometheusSvc),
  controlPlane: false,
  graylog: false,
};

const configJs = `// Generated by dev/serve-cluster.mjs for local development.
window.SB_CONFIG = ${JSON.stringify({
  k8sBase: "/k8s",
  contexts: contexts.map((c, i) => ({name: c.name, labels: {}, namespaces: "all", k8sBase: i === 0 ? "/k8s" : `/k8s/${c.name}`, local: i === 0})),
  operatorBase: "/operator/v1",
  helmBase: "/helm/v1",
  promBase: "/prometheus/api/v1",
  agentBase: "/operator/v1/agent",
  cpBase: "/controlplane/api/v2",
  graylogBase: "/graylog/api",
  upstreams,
  graylogOff: "the local development server does not proxy a log store",
  namespace,
  drNamespace: "ramen-ops",
  drHubNamespace: "dr-simplyblock",
  mode: "full",
  logoUrl: "https://simplyblock.io/assets/images/Logo-white.svg",
  authMode: "serviceaccount",
  token: "",
  mock: false,
}, null, 2)};
`;

// route maps a request path to [kubectl proxy port, upstream path], or null
// when the path is not proxied.
function route(p) {
  if (p.startsWith("/k8s/")) {
    const [, , first] = p.split("/");
    const named = contexts.find(c => c.name === first);
    return named ? [named.port, p.slice(`/k8s/${first}`.length) || "/"] : [local.port, p.slice("/k8s".length)];
  }
  for (const [prefix, svc, sub, on] of [
    ["/operator/v1/", operatorSvc, "/v1/", upstreams.operator],
    ["/helm/v1/", operatorSvc, "/v1/", upstreams.helm],
    ["/prometheus/api/v1/", prometheusSvc, "/api/v1/", upstreams.prometheus],
  ]) {
    if (p.startsWith(prefix)) return on ? [local.port, svcPath(svc) + sub + p.slice(prefix.length)] : "off";
  }
  if (p.startsWith("/controlplane/") || p.startsWith("/graylog/")) return "off";
  return null;
}

function proxy(req, res, port, upstreamPath, query) {
  const headers = {...req.headers};
  delete headers.host;
  delete headers.authorization;
  delete headers.cookie;
  delete headers.origin;
  const up = http.request({host: "127.0.0.1", port, method: req.method, path: upstreamPath + query, headers}, upRes => {
    res.writeHead(upRes.statusCode, upRes.headers);
    upRes.pipe(res);
  });
  up.on("error", err => { if (!res.headersSent) res.writeHead(502); res.end(String(err)); });
  // a watch streams until the browser leaves; the response closing is that signal
  // (the request's own close fires as soon as its body has been read)
  res.on("close", () => up.destroy());
  req.pipe(up);
}

const TYPES = {".html": "text/html", ".js": "application/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".json": "application/json", ".woff2": "font/woff2", ".png": "image/png"};

function serveFile(res, p) {
  let file = path.join(root, path.normalize(p));
  if (!file.startsWith(root + path.sep)) { res.writeHead(403); return res.end(); }
  let st;
  try { st = statSync(file); } catch { st = null; }
  // nginx falls back to index.html for unknown paths, so deep links reload
  if (!st || st.isDirectory()) { file = path.join(root, "index.html"); }
  res.writeHead(200, {"Content-Type": TYPES[path.extname(file)] || "application/octet-stream", "Cache-Control": "no-store"});
  createReadStream(file).pipe(res);
}

const LOOPBACK = /^(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/;
const server = http.createServer((req, res) => {
  if (!LOOPBACK.test(req.headers.host || "")) { res.writeHead(421); return res.end("misdirected request\n"); }
  const url = new URL(req.url, "http://localhost");
  if (url.pathname === "/config.js") {
    res.writeHead(200, {"Content-Type": "application/javascript", "Cache-Control": "no-store"});
    return res.end(configJs);
  }
  const r = route(url.pathname);
  if (r === "off") {
    res.writeHead(503, {"Content-Type": "application/json"});
    return res.end(JSON.stringify({kind: "Status", apiVersion: "v1", status: "Failure", code: 503, reason: "NotInDeployment", message: `${url.pathname} is not reachable from the local development server`}));
  }
  if (r) return proxy(req, res, r[0], r[1], url.search);
  if (req.method !== "GET" && req.method !== "HEAD") { res.writeHead(405); return res.end(); }
  serveFile(res, decodeURIComponent(url.pathname));
});

const [host, port] = listen.includes(":") ? [listen.slice(0, listen.lastIndexOf(":")) || "127.0.0.1", listen.slice(listen.lastIndexOf(":") + 1)] : ["127.0.0.1", listen];
server.listen(Number(port), host, () => {
  for (const c of contexts) console.log(`context ${c.name}: kubeconfig context ${c.kubeContext || "(current)"} via kubectl proxy on 127.0.0.1:${c.port}`);
  console.log(`upstreams in ${namespace}: operator=${upstreams.operator} prometheus=${upstreams.prometheus}`);
  console.log(`console on http://${host === "0.0.0.0" ? "localhost" : host}:${port}; writes go to the cluster with your kubeconfig's permissions`);
});

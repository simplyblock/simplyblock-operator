// Tests of the field-marker generator against the fixture API packages under
// testdata/: the paths each marker resolves to, and the annotations written
// from them.

package main

import (
	"reflect"
	"strings"
	"testing"
)

// The webhook table keeps a segment per JSON level, with "*" where the path
// crosses the values of a map, and the writers each field admits besides the
// operator. Lists add no segment, as in the annotation paths.
func TestCollectManagedFieldsCarrySegmentsAndWriters(t *testing.T) {
	_, managed, err := collect("./testdata/fixture/...")
	if err != nil {
		t.Fatalf("collect: %v", err)
	}
	want := Managed{
		"fixture.simplyblock.io/Widget": {"v1beta1": {
			{Path: "spec.byName.serial", Segments: []string{"spec", "byName", "*", "serial"}},
			{Path: "spec.inherited", Segments: []string{"spec", "inherited"}},
			{Path: "spec.owner", Segments: []string{"spec", "owner"}},
			{Path: "spec.parts.serial", Segments: []string{"spec", "parts", "serial"}},
			{Path: "spec.steward", Segments: []string{"spec", "steward"}, Writers: []string{"hub"}},
			{Path: "spec.tree.label", Segments: []string{"spec", "tree", "label"}},
			{Path: "status.phase", Segments: []string{"status", "phase"}},
		}},
	}
	if !reflect.DeepEqual(managed, want) {
		t.Fatalf("collect resolved\n  %+v\nwant\n  %+v", managed, want)
	}
}


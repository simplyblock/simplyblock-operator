// The rendered file registers one webhook per kind with spec fields, for
// UPDATE only, and leaves status out: status is written through its own
// subresource, which these webhooks do not see.
func TestRenderWebhookRegistersEachKindAndSkipsStatus(t *testing.T) {
	managed := Managed{
		"fixture.simplyblock.io/Widget": {"v1beta1": {
			{Path: "spec.owner", Segments: []string{"spec", "owner"}},
			{Path: "spec.steward", Segments: []string{"spec", "steward"}, Writers: []string{"hub"}},
			{Path: "status.phase", Segments: []string{"status", "phase"}},
		}},
		"fixture.simplyblock.io/Statusonly": {"v1beta1": {
			{Path: "status.phase", Segments: []string{"status", "phase"}},
		}},
	}
	plurals := map[string]string{
		"fixture.simplyblock.io/Widget":     "widgets",
		"fixture.simplyblock.io/Statusonly": "statusonlies",
	}
	out, err := renderWebhook(managed, plurals, "fixture")
	if err != nil {
		t.Fatalf("renderWebhook: %v", err)
	}
	src := string(out)
	for _, want := range []string{
		"// Code generated by hack/fieldmarkers. DO NOT EDIT.",
		"package fixture",
		"// +kubebuilder:webhook:path=/validate-operator-managed-fields,mutating=false,failurePolicy=fail," +
			"matchPolicy=Equivalent,sideEffects=None,groups=fixture.simplyblock.io,resources=widgets,verbs=update," +
			"versions=v1beta1,name=voperatormanaged-widgets.fixture.simplyblock.io,admissionReviewVersions=v1",
		`{Group: "fixture.simplyblock.io", Version: "v1beta1", Kind: "Widget"}: {`,
		`{Path: "spec.owner", Segments: []string{"spec", "owner"}},`,
		`{Path: "spec.steward", Segments: []string{"spec", "steward"}, Writers: []string{"hub"}},`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("rendered file lacks %q\n%s", want, src)
		}
	}
	for _, unwanted := range []string{"status.phase", "statusonlies", "Statusonly"} {
		if strings.Contains(src, unwanted) {
			t.Errorf("rendered file carries %q\n%s", unwanted, src)
		}
	}
}

func TestCollectResolvesEveryMarkedPath(t *testing.T) {
	kinds, _, err := collect("./testdata/fixture/...")
	if err != nil {
		t.Fatalf("collect: %v", err)
	}
	want := Kinds{
		"fixture.simplyblock.io/Widget": {
			markerOperatorManaged: {"v1beta1": {
				"spec.byName.serial", "spec.inherited", "spec.owner", "spec.parts.serial", "spec.steward",
				"spec.tree.label", "status.phase",
			}},
			markerInvisible: {"v1beta1": {
				"spec.bookkeeping", "spec.byName.serial", "spec.detail.token", "spec.parts.serial", "spec.tuning.token",
			}},
			markerAdvanced: {"v1beta1": {"spec.tuning"}},
		},
	}
	if !reflect.DeepEqual(kinds, want) {
		t.Fatalf("collect resolved\n  %v\nwant\n  %v", kinds, want)
	}
}

